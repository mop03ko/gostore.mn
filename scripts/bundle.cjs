// Joins the storefront scripts and stylesheets into app.js and app.css.
// The host serves HTTP/1.1 (six connections per origin), so 22 separate files arrived in
// several round-trip waves; one file each removes those waves. Edit the sources below, then run:
//   node scripts/bundle.cjs          rebuild and update index.html
//   node scripts/bundle.cjs --check  fail if app.js, app.css or index.html are stale
// Every script starts with 'use strict' and keeps its own IIFE, so joining them keeps their
// semantics; files are separated by ';' so one file's ending cannot merge with the next.
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const SCRIPTS=['product-policy.js','script.js','commerce-ui.js','store-server.js','account.js','catalog-navigation.js','brand-page.js','supplier.js','barcode.js','cargo.js','checkout.js','shop-tools.js','account-page.js','store-pages.js','product-page.js','customer-sync.js'];
const STYLES=['styles.css','catalog-navigation.css','brand-page.css','assets/fonts/fonts.css','product-page.css','commerce-ui.css'];
const read=f=>fs.readFileSync(path.join(root,f),'utf8').replace(/\r\n/g,'\n');
const header='/* Generated by scripts/bundle.cjs. Edit the source files, then rebuild. */\n';

function build(){
  const js=header+SCRIPTS.map(f=>`/* ==== ${f} ==== */\n${read(f).trimEnd()}\n;`).join('\n')+'\n';
  new vm.Script(js,{filename:'app.js'});
  // fonts.css lives in assets/fonts; make its relative font URLs absolute for the root bundle.
  const css=header+STYLES.map(f=>{let s=read(f).trimEnd();if(f.includes('/'))s=s.replace(/url\('\.\/([^']+)'\)/g,(_,u)=>`url('/${path.posix.dirname(f)}/${u}')`);return `/* ==== ${f} ==== */\n${s}`;}).join('\n')+'\n';
  const v=s=>crypto.createHash('sha256').update(s).digest('hex').slice(0,12);
  let html=read('index.html');
  const scriptTag=f=>new RegExp(`<script src="/${f.replace(/[.]/g,'\\.')}\\?v=[^"]+" defer></script>`);
  const styleTag=f=>new RegExp(`<link rel="stylesheet" href="/${f.replace(/[.]/g,'\\.')}\\?v=[^"]+">\\n?`);
  const appJs=`<script src="/app.js?v=${v(js)}" defer></script>`,appCss=`<link rel="stylesheet" href="/app.css?v=${v(css)}">`;
  if(/\/app\.js\?v=/.test(html)){html=html.replace(/<script src="\/app\.js\?v=[^"]+" defer><\/script>/,appJs).replace(/<link rel="stylesheet" href="\/app\.css\?v=[^"]+">/,appCss);}
  else{
    // First conversion: the first source tag becomes the bundle tag, the rest are removed.
    for(const [list,tag,app] of [[SCRIPTS,scriptTag,appJs],[STYLES,styleTag,appCss+'\n']])list.forEach((f,i)=>{const re=tag(f);if(!re.test(html))throw Error('Missing tag for '+f);html=html.replace(re,i===0?app:'');});
  }
  for(const f of [...SCRIPTS,...STYLES])if(html.includes('/'+f+'?v='))throw Error('index.html still references '+f);
  return {js,css,html};
}
const out=build(),check=process.argv.includes('--check');
const stale=[['app.js',out.js],['app.css',out.css],['index.html',out.html]].filter(([f,s])=>!fs.existsSync(path.join(root,f))||read(f)!==s).map(([f])=>f);
if(check){if(stale.length){console.error('Stale bundle: '+stale.join(', ')+'. Run node scripts/bundle.cjs');process.exit(1);}console.log('Bundle is current.');}
else{for(const [f,s] of [['app.js',out.js],['app.css',out.css],['index.html',out.html]])fs.writeFileSync(path.join(root,f),s);console.log('Wrote app.js ('+out.js.length+' B), app.css ('+out.css.length+' B); updated index.html'+(stale.length?'':' (no changes)'));}
