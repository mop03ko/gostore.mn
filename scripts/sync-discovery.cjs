// Shared category labels, search destinations and catalog photos for web and Expo.
const fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('script.js','utf8');
const categories=vm.runInNewContext(source.slice(source.indexOf('const categories = '),source.indexOf('const $ = '))+';categories');
const photos=JSON.parse(fs.readFileSync('assets/category-photos.json','utf8'));
const data=categories.map(c=>({id:c.id,name:c.name,query:c.query,image:photos[c.query]?.image||'',children:c.children.map(t=>({...t,image:photos[t.query]?.image||''}))}));
fs.writeFileSync('gostoremn/src/lib/discovery.json',JSON.stringify(data,null,2)+'\n');
fs.writeFileSync('catalog-discovery-data.js',"'use strict';\n// Generated by scripts/sync-discovery.cjs.\nwindow.GOStoreDiscovery="+JSON.stringify(data)+';\n');
console.log('Synchronized '+data.length+' shared categories.');
